function love.conf(t)
    t.title = "Fishbowl"
    t.version = "11.4"
    t.console = true  -- Enable console window for debug output (Windows)
    t.window.width = 1280
    t.window.height = 720
    t.window.resizable = true
    t.window.vsync = 1
    t.window.minwidth = 800
    t.window.minheight = 600
end
